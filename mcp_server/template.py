"""Generated MCP server — READ-ONLY, business-database-scoped.

Generated by the MCP Server Builder. Exposes a single tool, `run_query`, that
executes validated SELECT statements against one configured business database.
Writes, DDL, database-structure/metadata requests (SHOW/DESCRIBE/EXPLAIN),
cross-database access, and overly complex queries are all refused before they
ever reach the database — see the embedded `sql_validator` block below, which
is the exact module covered by the project's test suite.

Security: the database connection string is read from the MCP_DB_URL environment
variable, injected by the deployer at launch. No credentials are written to this
file on disk.

Runs over HTTP (streamable-http) so a host application can connect as an MCP
client and issue read-only queries.
"""

import os
import time

from fastmcp import FastMCP
from sqlalchemy import create_engine, text

